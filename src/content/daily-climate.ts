/** Clima típico de una fecha "AAAA-MM-DD". Usa un año bisiesto de referencia para que el 29 de febrero también exista. */
export function typicalClimate(date: string) {
  const [month, day] = [Number(date.slice(5, 7)), Number(date.slice(8, 10))];
  const index = Math.round((Date.UTC(2024, month - 1, day) - Date.UTC(2024, 0, 1)) / 86_400_000);
  const [max, min] = dailyClimate[index];
  return { max, min };
}
